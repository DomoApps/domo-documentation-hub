def main():
    with open("scripts/output/catalog-classified.json") as f:
        catalog = json.load(f)

    applied = 0
    for entry in catalog:
        fname = entry["filename"]
        if fname in MANUAL:
            dtype, note = MANUAL[fname]
            entry["type"] = dtype
            entry["type_confidence"] = "manual"
            entry["type_note"] = note
            applied += 1

    with open("scripts/output/catalog-classified.json", "w") as f:
        json.dump(catalog, f, indent=2, ensure_ascii=False)

    print(f"Applied {applied} manual classifications")

    # Print final tally
    counts = {}
    for e in catalog:
        counts[e["type"]] = counts.get(e["type"], 0) + 1
    print("\nFinal classification distribution:")
    for t, c in sorted(counts.items(), key=lambda x: -x[1]):
        print(f"  {t:25s} {c:4d}")


if __name__ == "__main__":
    main()
